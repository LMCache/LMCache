#!/bin/bash
# Write the env.sh that every other P2P skill script sources (one per LMCache instance).
# usage: gen_env.sh --coordinator-ip IP --peer-ip IP [--peer-ssh HOST] [--model ID] [--python-bin DIR]
#        [--home DIR] [--node-ip IP] [--instance-id ID] [--gpu N] [--l1-gb N] [--hf-home DIR]
#        [--mp-port 6700 --http-port 7700 --p2p-port 8700 --vllm-port 8300 --coordinator-port 12500]
#        [--peer-http-port N --peer-vllm-port N] [--rdma auto|on|off] [--ucx-rails N]
#        [--max-model-len 32768] [--gpu-mem-util 0.85] [--single-node a|b]
# --single-node a|b presets both instances' ports on one host (node ip and peer ip = 127.0.0.1).
set -euo pipefail
HOME_DIR="${P2P_HOME:-$HOME/lmcache-p2p}"; MODEL=Qwen/Qwen3-8B; PYBIN=""; HFH="${HF_HOME:-}"
COORD_IP=""; COORD_PORT=12500; NODE_IP=""; INSTANCE_ID=""; PEER_IP=""; PEER_SSH=""
MP=6700; HTTP=7700; P2P=8700; VLLM=8300; PEER_HTTP=""; PEER_VLLM=""
GPU=0; L1_GB=80; RDMA=auto; RAILS=""; MML=32768; GMU=0.85; SINGLE=""
while [ $# -gt 0 ]; do case "$1" in
  --home) HOME_DIR=$2;; --model) MODEL=$2;; --python-bin) PYBIN=$2;; --hf-home) HFH=$2;;
  --coordinator-ip) COORD_IP=$2;; --coordinator-port) COORD_PORT=$2;; --node-ip) NODE_IP=$2;; --instance-id) INSTANCE_ID=$2;;
  --peer-ip) PEER_IP=$2;; --peer-ssh) PEER_SSH=$2;; --mp-port) MP=$2;; --http-port) HTTP=$2;; --p2p-port) P2P=$2;; --vllm-port) VLLM=$2;;
  --peer-http-port) PEER_HTTP=$2;; --peer-vllm-port) PEER_VLLM=$2;; --gpu) GPU=$2;; --l1-gb) L1_GB=$2;; --rdma) RDMA=$2;; --ucx-rails) RAILS=$2;;
  --max-model-len) MML=$2;; --gpu-mem-util) GMU=$2;; --single-node) SINGLE=$2;;
  *) echo "unknown arg $1" >&2; exit 2;; esac; shift 2; done
if [ -n "$SINGLE" ]; then
  COORD_IP=127.0.0.1; NODE_IP=127.0.0.1; PEER_IP=127.0.0.1; RDMA=${RDMA/auto/off}
  case "$SINGLE" in a) MP=6700; HTTP=7700; P2P=8700; VLLM=8300; PEER_HTTP=7701; PEER_VLLM=8301; INSTANCE_ID=${INSTANCE_ID:-node-a}; HOME_DIR="$HOME_DIR/node-a";;
                    b) MP=6701; HTTP=7701; P2P=8701; VLLM=8301; PEER_HTTP=7700; PEER_VLLM=8300; INSTANCE_ID=${INSTANCE_ID:-node-b}; HOME_DIR="$HOME_DIR/node-b";;
                    *) echo "--single-node takes a or b" >&2; exit 2;; esac
fi
[ -n "$COORD_IP" ] || { echo "--coordinator-ip is required" >&2; exit 2; }
[ -n "$PEER_IP" ] || { echo "--peer-ip is required" >&2; exit 2; }
NODE_IP=${NODE_IP:-$(hostname -I | awk '{print $1}')}; INSTANCE_ID=${INSTANCE_ID:-p2p-$(hostname -s)}
PEER_HTTP=${PEER_HTTP:-$HTTP}; PEER_VLLM=${PEER_VLLM:-$VLLM}
PYBIN=${PYBIN:-$(dirname "$(command -v python)")}
# UCX multi-rail: NIXL >= 1.5 needs cuda_copy in UCX_TLS on GPU hosts; rails count paths and
# LAG bonds expose 2 paths each, so rails = devices x paths (see references/ucx-multirail.md).
UCX_BLOCK="# RDMA disabled or absent: UCX defaults (TCP fallback possible)"
ndev=$(ls -d /sys/class/infiniband/* 2>/dev/null | wc -l)
if [ "$RDMA" = on ] || { [ "$RDMA" = auto ] && [ "$ndev" -gt 0 ]; }; then
  if [ -z "$RAILS" ]; then paths=1; ls -d /sys/class/infiniband/*bond* >/dev/null 2>&1 && paths=2; RAILS=$(( ndev * paths )); [ "$RAILS" -gt 16 ] && RAILS=16; [ "$RAILS" -lt 1 ] && RAILS=1; fi
  devs=$(ls /sys/class/infiniband/ 2>/dev/null | sed 's/$/:1/' | paste -sd, -)
  UCX_BLOCK="export UCX_TLS=rc,sm,self,cuda_copy
export UCX_MAX_RMA_RAILS=$RAILS
export UCX_NET_DEVICES=$devs
export UCX_MULTI_LANE_MAX_RATIO=1000"
fi
mkdir -p "$HOME_DIR"
cat > "$HOME_DIR/env.sh" <<ENV
#!/bin/bash
# Generated by lmcache-p2p-launch/scripts/gen_env.sh on $(date -Iseconds). Edit freely.
export P2P_HOME="$HOME_DIR"
export PATH="$PYBIN:\$HOME/.local/bin:/usr/local/cuda/bin:\$PATH"
${HFH:+export HF_HOME="$HFH"}
export HF_HUB_OFFLINE=\${HF_HUB_OFFLINE:-1}
export MODEL="$MODEL"
export COORD_IP="$COORD_IP" COORD_PORT=$COORD_PORT
export NODE_IP="$NODE_IP" INSTANCE_ID="$INSTANCE_ID"
export MP_PORT=$MP HTTP_PORT=$HTTP P2P_PORT=$P2P VLLM_PORT=$VLLM
export PEER_IP="$PEER_IP" PEER_SSH="$PEER_SSH" PEER_HTTP_PORT=$PEER_HTTP PEER_VLLM_PORT=$PEER_VLLM
export GPU=\${GPU:-$GPU} L1_GB=\${L1_GB:-$L1_GB} MAX_MODEL_LEN=$MML GPU_MEM_UTIL=$GMU
export COORD_URL="http://\$COORD_IP:\$COORD_PORT"
export HTTP_URL="http://\$NODE_IP:\$HTTP_PORT" VLLM_URL="http://\$NODE_IP:\$VLLM_PORT"
export PEER_HTTP_URL="http://\$PEER_IP:\$PEER_HTTP_PORT" PEER_VLLM_URL="http://\$PEER_IP:\$PEER_VLLM_PORT"
export LMCACHE_LOG_LEVEL=\${LMCACHE_LOG_LEVEL:-INFO} PYTHONUNBUFFERED=1 PYTHONFAULTHANDLER=1
$UCX_BLOCK
ENV
echo "wrote $HOME_DIR/env.sh"; sed 's/^/  /' "$HOME_DIR/env.sh"
